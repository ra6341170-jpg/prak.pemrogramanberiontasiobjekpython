# lstrip() untuk trim whitespace karakter di awal atau sebelah kiri string
print(f"-- {text.lstrip()} --")
# output ↓
#
# --hello python
# -

# rstrip() untuk trim whitespace karakter di akhir atau sebelah kanan string
print(f"-- {text.rstrip()} --")
# output ↓
#
# -
# hello python--

# strip() untuk trim whitespace karakter di awal dan akhir string
print(f"-- {text.strip()} --")
# output ➜ --hello python--